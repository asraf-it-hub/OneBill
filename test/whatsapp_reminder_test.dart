import 'package:flutter_test/flutter_test.dart';
import 'package:onebill/core/localization/app_localizations.dart';
import 'package:onebill/features/auth/domain/auth_error_details.dart';

void main() {
  group('WhatsApp Payment Reminder & Bug Fixes Tests', () {
    test('WhatsApp Reminder localization keys exist for en, hi, and te', () {
      final requiredKeys = [
        'WhatsApp reminder',
        'Could not open WhatsApp',
        'This customer has no outstanding payments.',
        'Please enter a valid phone number for this customer.',
        'Hello',
        'YOUR PAYMENT SUMMARY',
        'Outstanding Invoices',
        'TOTAL OUTSTANDING',
        'Invoice Amount',
        'Balance Due',
        'Kindly settle your outstanding payments at your convenience.',
        'If you have already made any payments, please let us know.',
        'Thank you for your continued support! 🙏',
        'Use at least 8 characters.',
        'Password is required',
        'Please confirm your password',
        'Passwords do not match',
        'Checking reset link...',
        'Request new link',
        'Back to sign in',
        'Reset your password',
        'Generated by OneBill',
      ];

      for (final key in requiredKeys) {
        expect(appTranslations.containsKey(key), isTrue,
            reason: 'Missing key "$key" in appTranslations');
        final trans = appTranslations[key]!;
        expect(trans.containsKey('hi'), isTrue,
            reason: 'Missing Hindi translation for "$key"');
        expect(trans['hi']!.isNotEmpty, isTrue,
            reason: 'Empty Hindi translation for "$key"');
        expect(trans.containsKey('te'), isTrue,
            reason: 'Missing Telugu translation for "$key"');
        expect(trans['te']!.isNotEmpty, isTrue,
            reason: 'Empty Telugu translation for "$key"');
      }
    });

    test('WhatsApp phone number normalization formats correctly', () {
      String normalizePhone(String raw) {
        var clean = raw.replaceAll(RegExp(r'[^\d]'), '');
        if (clean.length == 10) {
          clean = '91$clean';
        }
        return clean;
      }

      expect(normalizePhone('9876543210'), '919876543210');
      expect(normalizePhone('+91 98765 43210'), '919876543210');
      expect(normalizePhone('919876543210'), '919876543210');
      expect(normalizePhone('14155552671'), '14155552671');
    });

    test('AuthErrorDetails maps Google Sign-In network errors to connectionProblem', () {
      final googleOfflineError =
          'PlatformException(network_error, com.google.android.gms.common.api.ApiException: 7: , null, null)';
      final details = AuthErrorDetails.fromError(googleOfflineError);
      expect(details.type, AuthErrorType.connectionProblem);
      expect(details.title, 'Connection problem');
      expect(details.message,
          'No internet connection. Please check your network and try again.');
    });

    test('AuthErrorDetails maps expired reset link to friendly expired message', () {
      final expiredError =
          'AuthException(message: Auth session missing!, statusCode: 400)';
      final details = AuthErrorDetails.fromError(expiredError);
      expect(details.type, AuthErrorType.somethingWentWrong);
      expect(details.title, 'Reset link expired');
      expect(details.message,
          'This password reset link has expired or has already been used. Please request a new link from the sign-in screen.');
    });

    test('AuthErrorDetails maps otp_expired and access_denied to Reset link expired', () {
      final otpError = 'error=access_denied&error_code=otp_expired';
      final details = AuthErrorDetails.fromError(otpError);
      expect(details.title, 'Reset link expired');
    });

    test('WhatsApp reminder message ends with italic OneBill footer', () {
      final buffer = StringBuffer();
      buffer.writeln('*Sri Lakshmi Stores*\n');
      buffer.writeln('━━━━━━━━━━━━━━━━\n');
      buffer.writeln('_Generated by OneBill_');
      final text = buffer.toString();
      expect(text.contains('━━━━━━━━━━━━━━━━\n\n_Generated by OneBill_'), isTrue);
    });
  });
}
